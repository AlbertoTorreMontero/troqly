import re, sys, time
from playwright.sync_api import sync_playwright, expect

BASE = 'http://localhost:3300'
errors = []
def watch(page, tag):
    page.on('console', lambda m: errors.append(f'[{tag}] {m.text}') if m.type == 'error' else None)
    page.on('pageerror', lambda e: errors.append(f'[{tag}] {e}'))

def shot(page, name):
    page.screenshot(path=f'/tmp/shots/{name}.png', full_page=False)

with sync_playwright() as p:
    b = p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
    host_ctx = b.new_context(viewport={'width': 820, 'height': 1180}, locale='es-ES', device_scale_factor=1)
    h = host_ctx.new_page(); watch(h, 'host')
    h.goto(BASE + '/')
    expect(h.get_by_text('Tus noches de juegos, en una app')).to_be_visible()
    shot(h, '01-bienvenida')
    h.get_by_role('link', name='Crear cuenta').click()
    h.fill('input[name=name]', 'Marta'); h.fill('input[name=email]', 'marta@test.com'); h.fill('input[name=password]', 'secreta123')
    h.get_by_role('button', name='Crear cuenta').click()
    expect(h.get_by_text('¡Bienvenido, Marta!')).to_be_visible()
    h.fill('input[name=name]', 'Los del jueves'); h.get_by_role('button', name='Crear grupo').click()
    expect(h.get_by_role('link', name='Abrir Mesa en vivo')).to_be_visible()
    print('✓ cuenta + grupo')
    # colección
    h.goto(BASE + '/collection')
    for name in ['Catan', 'Azul', 'Wingspan']:
        h.get_by_role('button', name=re.compile('Añadir')).first.click()
        h.fill('#q', name); h.wait_for_timeout(400)
        h.locator('[data-add]').first.select_option('owned' if name != 'Wingspan' else 'unplayed')
        h.wait_for_timeout(250)
        h.keyboard.press('Escape'); h.locator('.modal-back').click(position={'x': 5, 'y': 5})
    expect(h.get_by_text('3 juegos')).to_be_visible()
    shot(h, '02-coleccion')
    h.get_by_role('button', name=re.compile('Pile of Shame')).click()
    expect(h.locator('#list').get_by_text('Wingspan')).to_be_visible()
    print('✓ colección + filtros + Pile of Shame')
    # Mesa en vivo
    h.goto(BASE + '/live')
    h.locator('[data-g]').filter(has_text='Catan').click()
    h.get_by_role('button', name='Abrir mesa').click()
    h.wait_for_url(re.compile(r'/live/[A-Z0-9]{5}'))
    code = h.url.rsplit('/', 1)[1]
    expect(h.locator('img.qr')).to_be_visible()
    shot(h, '03-mesa-qr')
    print('✓ mesa', code)
    phones = []
    for i, (nick, loc) in enumerate([('Ana', 'es-ES'), ('Tom', 'en-GB'), ('Leo', 'es-MX')]):
        ctx = b.new_context(**p.devices['iPhone 13'], locale=loc)
        ph = ctx.new_page(); watch(ph, nick)
        ph.goto(f'{BASE}/m/{code}')
        ph.fill('input[name=nick]', nick)
        ph.locator('[data-e]').nth(i + 3).click()
        ph.locator('#nick button[type=submit], #nick button:not([type])').last.click()
        expect(ph.locator('.scorepad')).to_be_visible()
        phones.append(ph)
    expect(phones[1].get_by_text('Scoreboard')).to_be_visible()  # el móvil en inglés
    print('✓ 3 móviles dentro sin registrarse (es, en, es-MX)')
    # Todos apuntan a la vez
    phones[0].get_by_role('button', name='+5', exact=True).click()
    phones[1].get_by_role('button', name='+10').click()
    phones[2].get_by_role('button', name='+1', exact=True).click()
    phones[0].get_by_role('button', name='+1', exact=True).click()
    h.wait_for_timeout(600)
    rows = h.locator('.score-row')
    expect(rows.first).to_contain_text('Tom')
    expect(rows.first.locator('.pts')).to_have_text('10')
    expect(h.locator('.score-row', has_text='Ana').locator('.pts')).to_have_text('6')
    expect(phones[2].locator('.score-row', has_text='Tom').locator('.pts')).to_have_text('10')
    print('✓ marcador en vivo en todas las pantallas')
    h.get_by_role('button', name='Empezar turnos').click()
    h.get_by_role('button', name='Tirar').click()
    expect(phones[0].locator('.die').first).to_be_visible()
    h.get_by_role('button', name='Sortear').click()
    expect(phones[1].get_by_text(re.compile(r'goes first$'))).to_be_visible()
    shot(h, '04-mesa-marcador'); shot(phones[0], '05-movil-jugador'); shot(phones[1], '06-movil-ingles')
    print('✓ temporizador, dado y ¿quién empieza?')
    h.get_by_role('button', name=re.compile('Terminar partida')).click()
    h.get_by_role('button', name='Ver el podio').click()
    expect(h.get_by_text('¡Tom gana!')).to_be_visible()
    expect(phones[1].get_by_text('Tom wins!')).to_be_visible()
    expect(phones[0].locator('.podium')).to_be_visible()
    h.wait_for_timeout(1200)
    shot(h, '07-podio'); shot(phones[1], '08-podio-movil-en')
    with h.expect_download() as dl:
        h.get_by_role('button', name=re.compile('Compartir tarjeta')).click()
    dl.value.save_as('/tmp/shots/09-tarjeta.png')
    print('✓ podio + tarjeta para compartir')
    # Estadísticas y grupo
    h.goto(BASE + '/stats')
    expect(h.get_by_text('H-index').first).to_be_visible()
    shot(h, '10-estadisticas')
    h.goto(BASE + '/history')
    expect(h.get_by_text('Tom')).to_be_visible()
    h.goto(BASE + '/group')
    expect(h.get_by_text('Invita a tu gente')).to_be_visible()
    shot(h, '11-grupo')
    h.goto(BASE + '/suggest')
    expect(h.get_by_text('Nuestra apuesta')).to_be_visible()
    shot(h, '12-a-que-jugamos')
    print('✓ estadísticas, historial, grupo, ¿a qué jugamos?')
    # Reglas
    h.goto(BASE + '/rules')
    h.select_option('select[name=game]', label='Catan')
    h.set_input_files('input[name=files]', '/tmp/catan-rules.pdf')
    h.get_by_role('button', name='Subir y preparar').click()
    expect(h.locator('#ask')).to_be_visible(timeout=15000)
    h.fill('#ask input', '¿Puedo comerciar en el turno de otro jugador?')
    h.get_by_role('button', name='Preguntar').click()
    expect(h.get_by_text('Solo puedes comerciar durante tu propio turno')).to_be_visible()
    expect(h.get_by_role('button', name=re.compile('Pág. 2'))).to_be_visible()
    h.fill('#ask input', '¿Cuántos dragones hay?')
    h.get_by_role('button', name='Preguntar').click()
    expect(h.get_by_text('No aparece en el manual.').first).to_be_visible()
    h.get_by_role('button', name=re.compile('Pág. 2')).first.click()
    expect(h.locator('mark')).to_be_visible()
    shot(h, '13-reglas-cita')
    h.keyboard.press('Escape'); h.locator('[data-close]').click()
    print('✓ asistente de reglas: cita página, "no aparece", texto original')
    # Podcasts
    h.goto(BASE + '/podcasts')
    h.get_by_text('Mesa de Prueba').click()
    h.get_by_role('button', name='Seguir').click()
    h.get_by_text('Reseña de Catan').click()
    expect(h.get_by_text('Repaso a Catan tres décadas')).to_be_visible()
    expect(h.locator('a.chip', has_text='Catan')).to_be_visible()
    shot(h, '14-episodio')
    h.goto(BASE + '/game/1')
    expect(h.get_by_text('Escuchar sobre este juego')).to_be_visible()
    expect(h.get_by_text('Reseña de Catan')).to_be_visible()
    shot(h, '15-ficha-juego')
    print('✓ podcasts: seguir, resumen IA, juego ↔ episodio')
    # Cambio de idioma
    h.goto(BASE + '/settings')
    h.select_option('#lang', 'en')
    expect(h.get_by_text('Language', exact=True)).to_be_visible()
    h.goto(BASE + '/')
    expect(h.get_by_role('link', name='Open a Live Table')).to_be_visible()
    h.select_option('#theme', 'light') if h.locator('#theme').count() else None
    shot(h, '16-inicio-ingles')
    h.goto(BASE + '/settings'); h.select_option('#theme', 'light'); h.goto(BASE + '/stats')
    shot(h, '17-estadisticas-claro-en')
    print('✓ inglés + modo claro')
    b.close()

print('\nErrores de consola:', len(errors))
for e in errors[:20]: print('  ', e)
sys.exit(1 if errors else 0)
